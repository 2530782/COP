/**
 * Tablas de la base de datos (SRS 3.5: Usuario, Personal, Profesional, Servicio,
 * Horario disponible, Cita, Notificación) más Polígono, Reporte y Bitácora.
 *
 * El SQL funciona igual en PostgreSQL y en H2 (modo PostgreSQL).
 * Fechas como texto "AAAA-MM-DD", horas como "HH:MM" y momentos en milisegundos.
 * Los profesionales son usuarios con rol PROFESIONAL y su servicio_id (igual que en usuarios.json).
 */
object Esquema {

    fun crearTablas() {
        BaseDatos.ejecutar(
            """
            CREATE TABLE IF NOT EXISTS servicios (
                id VARCHAR(10) PRIMARY KEY,
                nombre VARCHAR(80) NOT NULL,
                descripcion VARCHAR(500) NOT NULL,
                duracion_minutos INTEGER NOT NULL,
                activo BOOLEAN NOT NULL DEFAULT TRUE
            )
            """.trimIndent()
        )

        BaseDatos.ejecutar(
            """
            CREATE TABLE IF NOT EXISTS usuarios (
                username VARCHAR(40) PRIMARY KEY,
                contrasena_hash VARCHAR(255) NOT NULL,
                nombre VARCHAR(120) NOT NULL,
                rol VARCHAR(20) NOT NULL,
                servicio_id VARCHAR(10),
                telefono VARCHAR(20) NOT NULL DEFAULT '',
                correo VARCHAR(120) NOT NULL DEFAULT '',
                activo BOOLEAN NOT NULL DEFAULT TRUE,
                intentos_fallidos INTEGER NOT NULL DEFAULT 0,
                bloqueado_hasta BIGINT NOT NULL DEFAULT 0,
                acepto_privacidad BOOLEAN NOT NULL DEFAULT FALSE,
                codigo_recuperacion VARCHAR(10),
                codigo_expira BIGINT NOT NULL DEFAULT 0,
                creado BIGINT NOT NULL
            )
            """.trimIndent()
        )

        BaseDatos.ejecutar(
            """
            CREATE TABLE IF NOT EXISTS horarios (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                profesional VARCHAR(40) NOT NULL,
                dia_semana INTEGER NOT NULL,
                hora_inicio VARCHAR(5) NOT NULL,
                hora_fin VARCHAR(5) NOT NULL
            )
            """.trimIndent()
        )

        BaseDatos.ejecutar(
            """
            CREATE TABLE IF NOT EXISTS citas (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                servicio_id VARCHAR(10) NOT NULL,
                profesional VARCHAR(40) NOT NULL,
                paciente VARCHAR(40),
                nombre_contacto VARCHAR(120),
                telefono_contacto VARCHAR(20),
                fecha VARCHAR(10) NOT NULL,
                hora VARCHAR(5) NOT NULL,
                estado VARCHAR(20) NOT NULL,
                notas VARCHAR(500) NOT NULL DEFAULT '',
                motivo VARCHAR(500) NOT NULL DEFAULT '',
                creado_por VARCHAR(20) NOT NULL,
                creado BIGINT NOT NULL,
                actualizado BIGINT NOT NULL
            )
            """.trimIndent()
        )

        BaseDatos.ejecutar(
            """
            CREATE TABLE IF NOT EXISTS notificaciones (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username VARCHAR(40) NOT NULL,
                cita_id INTEGER,
                titulo VARCHAR(120) NOT NULL,
                mensaje VARCHAR(500) NOT NULL,
                leida BOOLEAN NOT NULL DEFAULT FALSE,
                creado BIGINT NOT NULL
            )
            """.trimIndent()
        )

        BaseDatos.ejecutar(
            """
            CREATE TABLE IF NOT EXISTS poligonos (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nombre VARCHAR(120) NOT NULL,
                direccion VARCHAR(250) NOT NULL,
                latitud DOUBLE PRECISION NOT NULL,
                longitud DOUBLE PRECISION NOT NULL,
                horario VARCHAR(120) NOT NULL,
                telefono VARCHAR(40) NOT NULL,
                servicios VARCHAR(500) NOT NULL,
                es_principal BOOLEAN NOT NULL DEFAULT FALSE,
                aproximada BOOLEAN NOT NULL DEFAULT FALSE,
                activo BOOLEAN NOT NULL DEFAULT TRUE
            )
            """.trimIndent()
        )

        BaseDatos.ejecutar(
            """
            CREATE TABLE IF NOT EXISTS reportes (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username VARCHAR(40) NOT NULL,
                descripcion VARCHAR(1000) NOT NULL,
                dispositivo VARCHAR(120) NOT NULL DEFAULT '',
                creado BIGINT NOT NULL
            )
            """.trimIndent()
        )

        // COP-RS-06: bitácora de errores y eventos relevantes
        BaseDatos.ejecutar(
            """
            CREATE TABLE IF NOT EXISTS bitacora (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nivel VARCHAR(10) NOT NULL,
                mensaje VARCHAR(1000) NOT NULL,
                creado BIGINT NOT NULL
            )
            """.trimIndent()
        )
    }

    /** Copia los JSON de resources/data a la base. Solo si la base está vacía. */
    fun cargarDatosIniciales() {
        if (BaseDatos.entero("SELECT COUNT(*) FROM usuarios") == 0) {
            val json = JsonDataSource()
            val ahora = System.currentTimeMillis()

            for (s in json.servicios) {
                BaseDatos.ejecutar(
                    "INSERT INTO servicios (id, nombre, descripcion, duracion_minutos, activo) VALUES (?, ?, ?, ?, ?)",
                    s.id,
                    s.nombre,
                    s.descripcion,
                    s.duracionMinutos,
                    s.activo
                )
            }

            for (u in json.usuarios) {
                // Las contraseñas de usuarios.json se guardan CIFRADAS (COP-RC-03)
                BaseDatos.ejecutar(
                    """
                    INSERT INTO usuarios
                        (username, contrasena_hash, nombre, rol, servicio_id, telefono, correo, activo, acepto_privacidad, creado)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, TRUE, ?)
                    """.trimIndent(),
                    u.username.lowercase(),
                    Contrasenas.cifrar(u.password),
                    u.nombre,
                    u.rol,
                    u.servicioId,
                    u.telefono,
                    u.correo,
                    u.activo,
                    ahora
                )

                // Cada profesional atiende de lunes a viernes de 9:00 a 14:00
                if (u.rol == Roles.PROFESIONAL) {
                    for (dia in 1..5) {
                        BaseDatos.insertar(
                            "INSERT INTO horarios (profesional, dia_semana, hora_inicio, hora_fin) VALUES (?, ?, ?, ?)",
                            u.username.lowercase(),
                            dia,
                            "09:00",
                            "14:00"
                        )
                    }
                }
            }

            // Citas de citas.json (sirven como historial)
            for (c in json.citas) {
                insertarCitaInicial(c.servicioId, c.profesional, c.paciente, c.fecha, c.hora, c.estado, ahora)
            }

            // Algunas citas futuras para la demostración (siempre caen en días hábiles a las 9:00)
            insertarCitaInicial("FIS", "fisio", "ana", diaHabil(2), "09:00", EstadosCita.PENDIENTE, ahora)
            insertarCitaInicial("NUT", "nutri", "luis", diaHabil(3), "09:00", EstadosCita.CONFIRMADA, ahora)
            insertarCitaInicial("PSI", "psico", "sofia", diaHabil(4), "09:00", EstadosCita.PENDIENTE, ahora)
        }

        if (BaseDatos.entero("SELECT COUNT(*) FROM poligonos") == 0) {
            cargarPoligonos()
        }
    }

    private fun insertarCitaInicial(
        servicioId: String,
        profesional: String,
        paciente: String,
        fecha: String,
        hora: String,
        estado: String,
        ahora: Long
    ) {
        BaseDatos.insertar(
            """
            INSERT INTO citas
                (servicio_id, profesional, paciente, fecha, hora, estado, notas, motivo, creado_por, creado, actualizado)
            VALUES (?, ?, ?, ?, ?, ?, '', '', ?, ?, ?)
            """.trimIndent(),
            servicioId,
            profesional,
            paciente,
            fecha,
            hora,
            estado,
            Roles.USUARIO,
            ahora,
            ahora
        )
    }

    /** El n-ésimo día hábil (lunes a viernes) a partir de mañana, como "AAAA-MM-DD". */
    private fun diaHabil(n: Int): String {
        var fecha = Fechas.hoy()
        var cuenta = 0

        while (cuenta < n) {
            fecha = fecha.plusDays(1)

            if (fecha.dayOfWeek != DayOfWeek.SATURDAY && fecha.dayOfWeek != DayOfWeek.SUNDAY) {
                cuenta++
            }
        }

        return fecha.toString()
    }

